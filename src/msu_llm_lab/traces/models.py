"""Data models for ingested Langfuse RAG traces and diagnostic hypotheses."""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class FailureCategory(str, Enum):
    """Production failure modes across the RAG student counsellor stack."""
    ROUTING_FAILURE = "ROUTING_FAILURE"
    RETRIEVAL_FAILURE = "RETRIEVAL_FAILURE"
    GENERATION_FAILURE = "GENERATION_FAILURE"
    SOURCE_KNOWLEDGE_FAILURE = "SOURCE_KNOWLEDGE_FAILURE"
    NO_FAILURE_DETECTED = "NO_FAILURE_DETECTED"


class ObservationSpan(BaseModel):
    """An individual span, generation, or retrieval observation in a trace."""
    id: str = Field(description="Unique observation or span identifier")
    name: str = Field(description="Name of the observation step (e.g. 'router', 'retrieval', 'llm-generation')")
    type: str = Field(default="span", description="Type of observation: span, generation, or event")
    start_time: Optional[str] = None
    end_time: Optional[str] = None
    latency_ms: float = Field(default=0.0, ge=0.0)
    input_data: Optional[Any] = None
    output_data: Optional[Any] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)


class TraceRecord(BaseModel):
    """Canonical model for an ingested Langfuse trace execution."""
    id: str = Field(description="Unique Langfuse trace ID")
    timestamp: str = Field(description="ISO-8601 UTC timestamp of execution")
    session_id: Optional[str] = Field(default=None, description="Student session or conversation ID")
    user_id: Optional[str] = Field(default="[REDACTED_USER]", description="Anonymized user identifier")
    input_query: str = Field(description="Raw student query submitted to admissions assistant")
    output_response: str = Field(description="Final answer generated by admissions assistant")
    latency_ms: float = Field(default=0.0, ge=0.0)
    total_tokens: int = Field(default=0, ge=0)
    prompt_tokens: int = Field(default=0, ge=0)
    completion_tokens: int = Field(default=0, ge=0)
    spans: List[ObservationSpan] = Field(default_factory=list, description="Subordinate trace spans")
    tags: List[str] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)


class DiagnosisHypothesis(BaseModel):
    """Candidate diagnosis hypothesis with supporting evidence and confidence score.
    
    Acceptance Criteria: Must be explicitly presented as a candidate hypothesis,
    never as a deterministic ground-truth verdict.
    """
    trace_id: str
    category: FailureCategory
    confidence: float = Field(ge=0.0, le=1.0, description="Hypothesis confidence level (0.0 to 1.0)")
    hypothesis: str = Field(description="Human-readable diagnosis explaining why the query failed")
    evidence: List[str] = Field(default_factory=list, description="Supporting telemetry or text excerpts")
    suggested_action: str = Field(description="Actionable remediation recommendation")


class TraceDiagnosticReport(BaseModel):
    """Aggregated diagnostic report over a batch of imported traces."""
    total_traces: int
    diagnosed_failures: int
    category_counts: Dict[str, int]
    mean_latency_ms: float
    total_tokens: int
    diagnoses: List[DiagnosisHypothesis]
